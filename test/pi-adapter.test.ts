/** Janus by script: each run takes the next step; closures name intents by label. */
function janus(steps: Array<{ kindle?: boolean; close?: string[] }>): Decide {
  return (names, state, questions) => {
    const out: Record<string, number | Probs> = {};
    if (names.includes("focus")) {
      const step = steps.shift() ?? {};
      const none = String(state?.intent_stack ?? "").startsWith("(no open");
      out.focus = step.kindle ? { [none ? "new_root" : "deepen"]: 0.92 } : { continue: 0.95 };
      for (const n of names) {
        if (!n.startsWith("close.")) continue;
        const label = /"([^"]+)"/.exec(questions[n]!.instructions)?.[1] ?? "";
        out[n] = step.close?.includes(label) ? { success: 0.93, open: 0.03 } : { open: 0.96 };
      }
      return out;
    }
    for (const n of names) {
      if (n.startsWith("close.")) out[n] = { open: 0.96 };
      else if (n.startsWith("scope.")) out[n] = { project_personal: 0.9 };
      else if (n.startsWith("sensitive.")) out[n] = 0.02;
      else if (n.startsWith("urgency.")) out[n] = { caption: 0.9 };
      else if (n === "inject_any" || n.startsWith("rel.")) out[n] = 0.1;
      else if (n.startsWith("use.")) out[n] = { referenced: 0.8 };
      else if (n.startsWith("effect.")) out[n] = { no_effect: 1 };
      else if (n.startsWith("comply.")) out[n] = { complied: 0.9 };
    }
    return out;
  };
}

