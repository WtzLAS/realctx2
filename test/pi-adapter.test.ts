describe("the context hook", () => {
  it("applies edits to one request by aligning messages with the projection, or changes nothing", () => {
    const u = (text: string, timestamp: number) => ({ role: "user", content: text, timestamp }) as never;
    const a = (text: string, timestamp: number) => ({ role: "assistant", content: [{ type: "text", text }], timestamp }) as never;
    const sys = { role: "system", content: "prompt" } as never;
    const messages = [sys, u("one", 1), a("two", 2), u("three", 3), a("four", 4), u("queued", 9)];
    const projection = [
      { id: "e1", messages: [sys, messages[1]!] },
      { id: "state", messages: [] },
      { id: "e2", messages: [messages[2]!] },
      { id: "e3", messages: [messages[3]!] },
      { id: "e4", messages: [messages[4]!] },
    ];
    const out = applyEditsToMessages(messages, projection, [{ targetId: "e2", replacement: "[t:aaaaaaaa] folded" }, { targetId: "e3", replacement: null }])!;
    expect(out.map((m) => (m as { role: string }).role)).toEqual(["system", "user", "assistant", "assistant", "user"]);
    expect((out[2] as { content: unknown }).content).toEqual([{ type: "text", text: "[t:aaaaaaaa] folded" }]);
    expect(out.at(-1)).toBe(messages.at(-1)); // what follows the projection is kept
    expect(applyEditsToMessages(messages, projection, [{ targetId: "nope", replacement: null }])).toBeNull();
    // a projection that does not line up changes nothing
    expect(applyEditsToMessages([sys, u("other", 7)], projection, [{ targetId: "e2", replacement: null }])).toBeNull();
  });
});

describe("pressure, compaction and name conflicts in pi", () => {
  it("folds under pressure with persisted edits, and hands pi a realctx2 compaction when it compacts", async () => {
    const cwd = repo();
    const r = await piRig({ cwd, config: { context: { maxWindow: 32000, climb: { enabled: false } } }, settings: { compaction: { enabled: false, keepRecentTokens: 1500, reserveTokens: 2000 } } });
    let folds = 0;
    r.aux.push({
      when: '"narrative"',
      reply: () => {
        folds++;
        return { narrative: `Fold ${folds}: I ran a series of commands and collected their output.`, knowledge: [{ evaluation: "good", fact: `Fact ${folds}: \`echo\` prints its arguments.`, subject: "shell" }] };
      },
    });
    r.decision.handler = janus([]);
    const big = (i: number) => ({ text: `step ${i}`, tools: [{ name: "bash", args: { command: `echo ${filler(1150, `p${i}_`)}` } }] });
    const peak: number[] = [];
    for (let i = 0; i < 14; i++) r.main.push((call) => (peak.push(Math.ceil(call.text.length / 4)), big(i)));
    r.main.push({ text: "finished the series" });
    await r.prompt("run the series");
    expect(r.errors).toEqual([]);
    const b = r.branch();
    const records = b.filter((e) => e.customType === "realctx2.consolidation").map((e) => e.raw.data.record);
    expect(records.filter((x: { kind: string }) => x.kind === "palim").length).toBeGreaterThanOrEqual(1);
    // the window never overflowed: occupancy stayed bounded while 14 rounds of ~2.6K tokens went by
    expect(Math.max(...peak)).toBeLessThan(32000);
    expect(r.calls.at(-1)!.text).toContain("· consolidated earlier work]\nNarrative: Fold");
    expect(r.calls.at(-1)!.text).toContain("step 13"); // the working tail is still raw
    expect(r.calls.at(-1)!.text).not.toMatch(/^assistant: step 2$/m);
    expect(r.ui.notes.filter((n) => n.level === "warning")).toEqual([]);
    // every edit pi persisted targets an entry it can edit, and omitted rounds are whole
    const edits = b.filter((e) => e.type === "context_edit");
    expect(edits.length).toBeGreaterThan(8);
    const roles = r.calls.at(-1)!.roles;
    for (let i = 0; i < roles.length; i++) if (roles[i] === "toolResult") expect(["assistant", "toolResult"]).toContain(roles[i - 1]);

    // /compact: pi asks, realctx2 answers with its own summary and keeps the working tail
    const before = folds;
    await r.session.compact("keep the echo facts");
    expect(folds).toBe(before + 1);
    const after = r.branch();
    const compaction = r.session.sessionManager.getBranch().find((e) => e.type === "compaction") as unknown as { id: string; summary: string; firstKeptEntryId: string; fromHook?: boolean; details?: { realctx2?: string } };
    expect(compaction.fromHook).toBe(true);
    expect(compaction.summary).toMatch(/^\[t:[0-9a-z]{8} · compacted earlier work\]\nNarrative: Fold/);
    const record = after.filter((e) => e.customType === "realctx2.consolidation").map((e) => e.raw.data.record).find((x: { kind: string }) => x.kind === "compaction")!;
    expect(record).toMatchObject({ id: compaction.details!.realctx2, anchorId: compaction.id });
    // the earlier fold is a child of the compaction: recall still descends through it
    expect(record.children.some((c: { id?: string }) => c.id && records.some((x: { id: string }) => x.id === c.id))).toBe(true);
    r.main.push({ text: "what did the earlier steps show?", tools: [{ name: "recall", args: { id: record.id } }] }, { text: "ok" });
    await r.prompt("check the archive");
    const recalled = r.branch().filter((e) => e.role === "toolResult" && e.raw.message.toolName === "recall").at(-1)!;
    expect(recalled.raw.message.isError).toBe(false);
    expect(recalled.text).toMatch(/^\[t:[0-9a-z]{8} · compacted earlier work · one layer down · \d+ items\]\n\[t:[0-9a-z]{8} · consolidated earlier work\]\nNarrative: Fold \d/);
    expect(r.calls.at(-2)!.text).toContain("compacted earlier work]"); // the model sees pi's compaction summary, written by realctx2
    await r.shutdown();
  }, 120_000);

  it("skips a tool whose name another extension already uses, and reports it", async () => {
    const cwd = repo();
    const { DefaultResourceLoader } = await import("@earendil-works/pi-coding-agent");
    const orig = DefaultResourceLoader.prototype.reload;
    // another extension, loaded first, owns `search`
    const other = (pi: { registerTool(def: unknown): void }) => pi.registerTool({ name: "search", label: "Web search", description: "Search the web", parameters: { type: "object", properties: { q: { type: "string" } } }, execute: async () => ({ content: [{ type: "text", text: "web results" }], details: {} }) });
    const patched = async function (this: InstanceType<typeof DefaultResourceLoader>) {
      (this as unknown as { extensionFactories: unknown[] }).extensionFactories.unshift({ name: "websearch", factory: other });
      DefaultResourceLoader.prototype.reload = orig;
      return orig.call(this);
    };
    DefaultResourceLoader.prototype.reload = patched as typeof orig;
    const r = await piRig({ cwd });
    DefaultResourceLoader.prototype.reload = orig;
    const note = r.ui.notes.find((n) => n.level === "error");
    expect(note?.text).toMatch(/^realctx2: tool name "search" is already used by another extension \(<inline:websearch>\): realctx2's search tool was not registered \(rename it with tools\.names in config\.json\)$/);
    // the other extension's tool is intact, and ours are there except `search`
    r.decision.handler = janus([{}, {}]);
    r.main.push({ text: "searching", tools: [{ name: "search", args: { q: "x" } }] }, { text: "done" });
    await r.prompt("search the web");
    expect(r.branch().find((e) => e.role === "toolResult")!.text).toBe("web results");
    // the prompt section does not advertise a tool realctx2 does not have
    expect(r.calls[0]!.system).toContain("<realctx2>");
    expect(r.calls[0]!.system).not.toContain("- search looks through memory and earlier turns");
    expect(r.calls[0]!.system).toContain("recall(id) opens one layer");
    r.ui.notes.length = 0;
    await r.prompt("/realctx2 doctor");
    expect(r.ui.notes[0]!.text).toMatch(/✗ tool name "search" is already used by another extension/);
    await r.shutdown();
  }, 60_000);
});
