    r.decision.handler = janus([]);
    await r.prompt('/realctx2 remember "Never edit files in src/db/generated; they are regenerated by `pnpm db:generate`." --kind rule --severity must --urgency immediate --scope personal --path src/db/generated/');
    await r.prompt('/realctx2 remember "users rows are soft-deleted via deletedAt." --scope personal --urgency hint --path src/db/schema.ts');
