describe("the context hook", () => {
  it("applies edits to one request by aligning messages with the projection, or changes nothing", () => {
    const u = (text: string, timestamp: number) => ({ role: "user", content: text, timestamp }) as never;
    const a = (text: string, timestamp: number) => ({ role: "assistant", content: [{ type: "text", text }], timestamp }) as never;
    const sys = { role: "system", content: "prompt" } as never;
    const messages = [sys, u("one", 1), a("two", 2), u("three", 3), a("four", 4), u("queued", 9)];
    const projection = [
      { id: "e1", messages: [sys, messages[1]!] },
      { id: "state", messages: [] },
      { id: "e2", messages: [messages[2]!] },
      { id: "e3", messages: [messages[3]!] },
      { id: "e4", messages: [messages[4]!] },
    ];
    const out = applyEditsToMessages(messages, projection, [{ targetId: "e2", replacement: "[t:aaaaaaaa] folded" }, { targetId: "e3", replacement: null }])!;
    expect(out.map((m) => (m as { role: string }).role)).toEqual(["system", "user", "assistant", "assistant", "user"]);
    expect((out[2] as { content: unknown }).content).toEqual([{ type: "text", text: "[t:aaaaaaaa] folded" }]);
    expect(out.at(-1)).toBe(messages.at(-1)); // what follows the projection is kept
    expect(applyEditsToMessages(messages, projection, [{ targetId: "nope", replacement: null }])).toBeNull();
    // a projection that does not line up changes nothing
    expect(applyEditsToMessages([sys, u("other", 7)], projection, [{ targetId: "e2", replacement: null }])).toBeNull();
  });
});

