describe("the context hook", () => {
  it("applies edits to one request by aligning messages with the projection, or changes nothing", () => {
    const u = (text: string, timestamp: number) => ({ role: "user", content: text, timestamp }) as never;
    const a = (text: string, timestamp: number) => ({ role: "assistant", content: [{ type: "text", text }], timestamp }) as never;
    const sys = { role: "system", content: "prompt" } as never;
    const messages = [sys, u("one", 1), a("two", 2), u("three", 3), a("four", 4), u("queued", 9)];
    const projection = [
      { id: "e1", messages: [sys, messages[1]!] },
      { id: "state", messages: [] },
      { id: "e2", messages: [messages[2]!] },
      { id: "e3", messages: [messages[3]!] },
      { id: "e4", messages: [messages[4]!] },
    ];
    const out = applyEditsToMessages(messages, projection, [{ targetId: "e2", replacement: "[t:aaaaaaaa] folded" }, { targetId: "e3", replacement: null }])!;
    expect(out.map((m) => (m as { role: string }).role)).toEqual(["system", "user", "assistant", "assistant", "user"]);
    expect((out[2] as { content: unknown }).content).toEqual([{ type: "text", text: "[t:aaaaaaaa] folded" }]);
    expect(out.at(-1)).toBe(messages.at(-1)); // what follows the projection is kept
    expect(applyEditsToMessages(messages, projection, [{ targetId: "nope", replacement: null }])).toBeNull();
    // a projection that does not line up changes nothing
    expect(applyEditsToMessages([sys, u("other", 7)], projection, [{ targetId: "e2", replacement: null }])).toBeNull();
  });
});

describe("the Working row in before_agent_start", () => {
  const ctxWith = (idle: () => boolean) => {
    const calls: string[] = [];
    const ui = { setWorkingMessage: (m?: string) => void calls.push(`message:${m ?? ""}`), setWorkingVisible: (v: boolean) => void calls.push(`visible:${v}`) };
    return { calls, ctx: { hasUI: true, ui: ui as never, isIdle: idle } };
  };
  const wait = (ms: number) => new Promise((r) => setTimeout(r, ms));

  it("clears the row it raised when pi goes idle without starting the run", async () => {
    // pi's preparation failed after the hook: no agent_start, no agent_end to clear the row
    const { calls, ctx } = ctxWith(() => true);
    const row = workingRow(ctx, { started: () => false, pollMs: 5 });
    row.show(WORKING_MESSAGE);
    row.restore();
    await wait(40);
    expect(calls).toEqual([`message:${WORKING_MESSAGE}`, "visible:true", "message:", "visible:false", "visible:true"]);
  });

  it("leaves the row to pi once the run starts, and waits while pi is still preparing", async () => {
    let started = false;
    let idle = false;
    const { calls, ctx } = ctxWith(() => idle);
    const row = workingRow(ctx, { started: () => started, pollMs: 5 });
    row.show(WORKING_MESSAGE);
    row.restore();
    await wait(30); // preparing: neither started nor idle
    started = true;
    await wait(20);
    idle = true; // the run finished: agent_end already cleared the row
    await wait(20);
    expect(calls).toEqual([`message:${WORKING_MESSAGE}`, "visible:true", "message:"]);
    // a context without the UI methods (rpc, print) gets no row and nothing to restore
    const bare = workingRow({ hasUI: false, ui: {} as never, isIdle: () => true }, { started: () => false, pollMs: 5 });
    bare.show(WORKING_MESSAGE);
    bare.restore();
    await wait(20);
  });

  it("watches the interrupt key in pi's TUI only, without consuming it", () => {
    const listeners = new Set<(d: string) => unknown>();
    const ui = { onTerminalInput: (h: (d: string) => unknown) => (listeners.add(h), () => void listeners.delete(h)) };
    const w = interruptWatch({ hasUI: true, mode: "tui", ui: ui as never });
    expect(w.active).toBe(true);
    const send = (d: string) => [...listeners].map((h) => h(d));
    expect(send("a")).toEqual([undefined]);
    expect(w.signal.aborted).toBe(false);
    expect(send("\x1b")).toEqual([undefined]); // pi's editor still gets the key and aborts the run
    expect(w.signal.aborted).toBe(true);
    w.dispose();
    expect(listeners.size).toBe(0);
    // rpc and print have no terminal to watch
    for (const ctx of [{ hasUI: true, mode: "rpc" as const, ui: ui as never }, { hasUI: false, mode: "print" as const, ui: {} as never }]) {
      const off = interruptWatch(ctx);
      expect(off.active).toBe(false);
      off.dispose();
    }
    expect(listeners.size).toBe(0);
    expect(isInterruptKey("\x1b")).toBe(true);
    expect(isInterruptKey("\r")).toBe(false);
  });

  it("starts prompts immediately without blocking even when the decision endpoint hangs", async () => {
    const cwd = repo();
    const r = await piRig({ cwd, mode: "tui", config: { janus: { lateWaitMs: 200, timeoutMs: 8000, debounceMs: 5000 } } });
    expect(r.errors).toEqual([]);
    let release: () => void = () => undefined;
    const hung = new Promise<void>((res) => (release = res));
    r.decision.handler = async () => {
      await hung;
      return {};
    };
    r.main.push({ text: "answered immediately" });
    const t0 = Date.now();
    await r.prompt("add an email column to users");
    const took = Date.now() - t0;
    release();
    expect(r.errors).toEqual([]);
    // Prompt never blocked on Janus
    expect(took).toBeLessThan(2000);
    expect(r.calls.at(-1)?.text).toContain("user: add an email column to users");
    await r.shutdown();
  }, 20_000);
});

