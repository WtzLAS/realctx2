    expect(classifier).toMatchObject({ id: "jev-test", type: "classifier", api: "typesafe-system-one" });
    r.decision.handler = () => ({ risky: 0.9, kind: { bug: 0.7, feature: 0.3 } });
    const classified = await registry.classify(classifier, { state: { text: "drop table users" }, questions: { risky: { type: "bool", instructions: "Is this risky?", criteria: { true: "yes", false: "no" } }, kind: { type: "choice", instructions: "Kind?", criteria: { bug: "a bug", feature: "a feature" } } } });
